#!/usr/bin/env bash
# P0-6: write fdl/index from the fdl/ tree (format 1; see src/loaders.c).
#   scripts/gen-fdl-index.sh [FDL_DIR]          -> rewrites FDL_DIR/index
#   scripts/gen-fdl-index.sh --check [FDL_DIR]  -> exit 1 if FDL_DIR/index is stale
# The chip table is the one menu.sh soc_profile and the C core use; spdhost
# refuses an index whose soc rows disagree with its own build.
set -euo pipefail
export LC_ALL=C
check=0
if [[ ${1:-} == --check ]]; then check=1; shift; fi
here=$(cd "$(dirname "$0")" && pwd)
fdl=${1:-$here/../fdl}
fdl=$(cd "$fdl" && pwd)

gen() {
	echo "# spdhost fdl index. Generated by scripts/gen-fdl-index.sh -- do not edit by hand."
	echo "# file SHA256 KIND SOC ADDR PATH   (PATH relative to this folder)"
	echo "# pair SOC MODEL FDL1 FDL2         (MODEL = brand or brand/model, menu.sh DEVICE)"
	echo "spdhost-fdl-index 1"
	echo "soc ums9230 fdl1=0x65000800 fdl2=0x9efffe00 stub=0x65015f08 stub_alt=0x65015f48"
	echo "soc ums512 fdl1=0x5500 fdl2=0x9efffe00 stub=0x3ee8 stub_alt=0x3f48"
	echo "soc sc9863a fdl1=0x5000 fdl2=0x9efffe00 stub=0x4ee8 stub_alt=0x4f48"
	local rel soc base kind addr sha dir model
	declare -A f1addr=([ums9230]=0x65000800 [ums512]=0x5500 [sc9863a]=0x5000)
	while IFS= read -r rel; do
		soc=${rel%%/*}
		[[ -n ${f1addr[$soc]:-} ]] || { echo "gen-fdl-index: $rel: not under a known chip folder" >&2; return 1; }
		[[ $rel != *[[:space:]]* ]] || { echo "gen-fdl-index: $rel: whitespace in path" >&2; return 1; }
		base=${rel##*/}
		case $base in
			fdl1-dl.bin) kind=fdl1; addr=${f1addr[$soc]} ;;
			fdl2-dl.bin) kind=fdl2; addr=0x9efffe00 ;;
			fdl2-cboot.bin) kind=cboot; addr=- ;;
			custom_exec_no_verify_*.bin)
				kind=stub
				addr=${base#custom_exec_no_verify_}; addr=0x${addr%.bin}
				[[ $rel == "$soc/$base" ]] || { echo "gen-fdl-index: $rel: stubs live in <chip>/" >&2; return 1; }
				;;
			index) continue ;;
			*) echo "gen-fdl-index: $rel: unknown file kind" >&2; return 1 ;;
		esac
		sha=$(sha256sum "$fdl/$rel" | cut -d' ' -f1)
		echo "file $sha $kind $soc $addr $rel"
	done < <(cd "$fdl" && find . -type f ! -name index | sed 's#^\./##' | sort)
	while IFS= read -r dir; do
		[[ -f $fdl/$dir/fdl2-dl.bin ]] || continue
		soc=${dir%%/*}
		model=${dir#*/}
		model=${model/\/alternatif\//\/}
		model=${model/\/alternativ\//\/}
		echo "pair $soc $model $dir/fdl1-dl.bin $dir/fdl2-dl.bin"
	done < <(cd "$fdl" && find . -type f -name fdl1-dl.bin | sed 's#^\./##; s#/fdl1-dl.bin$##' | sort)
	echo "end"
}

out=$(gen)
if (( check )); then
	if [[ ! -f $fdl/index ]] || [[ $(cat "$fdl/index") != "$out" ]]; then
		echo "fdl/index is stale: run scripts/gen-fdl-index.sh" >&2
		diff <(cat "$fdl/index" 2>/dev/null) <(printf '%s\n' "$out") >&2 || true
		exit 1
	fi
	echo "fdl/index is current ($(grep -c '^file ' "$fdl/index") files, $(grep -c '^pair ' "$fdl/index") pairs)"
	exit 0
fi
printf '%s\n' "$out" >"$fdl/index"
echo "wrote $fdl/index ($(grep -c '^file ' "$fdl/index") files, $(grep -c '^pair ' "$fdl/index") pairs)"
